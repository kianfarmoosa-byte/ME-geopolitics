export function getEraRelationships(
  allRelationships: GeopoliticalRelationship[],
  eraId: string | 'all'
): GeopoliticalRelationship[] {
  if (eraId === 'all') {
    return allRelationships;
  }

  const era = TIMELINE_ERAS.find((e) => e.id === eraId);
  if (!era) return allRelationships;

  const activeSet = new Set(era.activeRelationshipIds);
  const overrides = era.overrides || {};

  return allRelationships
    .filter((rel) => activeSet.has(rel.id))
    .map((rel) => {
      const override = overrides[rel.id];
      if (override) {
        return {
          ...rel,
          ...override,
        };
      }
      return rel;
    });
}
